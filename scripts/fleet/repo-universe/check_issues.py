#!/usr/bin/env python3
"""Repo-universe issue checker (#1651, piece 2 of #1511).

Scheduled, read-only consumer of the piece-1 inventory
(`doc/fleet/repo-universe.yaml`, generated by generate.py): for every
repo whose effective watch is `issues`, fetch all issues from the
GitHub API (paginated, pull requests filtered out), diff them against
the persisted per-repo state, and emit a dated delta report.

Semantics:

- First run for a repo BASELINES it: all current issues are recorded
  and the report shows counts only — a first run never dumps the full
  history as "new".
- Later runs report new issues, changed issues (title/state/
  updated_at moved; open->closed is reported as closed, closed->open
  as reopened), and nothing else. A run whose upstream data is
  identical to the persisted state produces an empty delta and does
  not churn state beyond the run timestamp.
- A failed fetch is an explicit ERROR line in the report (and a
  non-zero exit); the repo's persisted state is left untouched, so a
  failure never masquerades as an empty repository.
- The checker performs NO GitHub writes. Pull-in / mirror /
  track-resolve behaviour is piece 3 (#1652), out of scope here.

State lives OUTSIDE the repo (default
`~/.local/state/repo-universe-issue-checker/`): `state.json` plus one
dated report per run (`report-YYYY-MM-DD.md`, suffixed if a day has
several runs). Schedule: systemd units in the `systemd/` directory
beside this file, following the infra/github-backup convention
(oneshot service + daily timer, Persistent, RandomizedDelaySec).

Usage:
    check_issues.py [--inventory doc/fleet/repo-universe.yaml]
                    [--state-dir ~/.local/state/repo-universe-issue-checker]
                    [--fixture fixture.json] [--now 2026-11-01T00:00:00Z]

`--fixture` replaces the GitHub fetch with a JSON file mapping
`owner/repo` -> a list of issue objects (same shape as the API), or
`{"error": "..."}` for a repo whose fetch should fail. Fixture mode
is how the tests and dry runs exercise the checker without touching
GitHub. Stdlib only.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ISSUE_FIELDS = ("number", "state", "title", "updated_at", "html_url")


class FetchError(Exception):
    """A repo's issue fetch failed; carries a human-readable reason."""


def parse_inventory(text: str) -> list[str]:
    """Return the repos whose effective watch is `issues`.

    The inventory is a maintained artifact with a fixed shape (see
    generate.py): a top-level `overrides:` mapping and a `repos:` list
    of flat entries. Overrides win over the per-repo watch value, the
    same rule the generator applies when it emits the artifact.
    """
    overrides: dict[str, dict] = {}
    repos: list[dict] = []
    section = None
    current: dict | None = None
    override_name: str | None = None
    for raw in text.splitlines():
        if raw.startswith("overrides:"):
            section = "overrides"
            continue
        if raw.startswith("repos:"):
            section = "repos"
            continue
        if section == "overrides":
            m = re.match(r"^  ([\w.-]+/[\w.-]+):\s*$", raw)
            if m:
                override_name = m.group(1)
                overrides.setdefault(override_name, {})
                continue
            m = re.match(r"^    (class|watch):\s*(\S+)\s*$", raw)
            if m and override_name:
                overrides[override_name][m.group(1)] = m.group(2)
            continue
        if section == "repos":
            m = re.match(r"^  - name:\s*(\S+)\s*$", raw)
            if m:
                current = {"name": m.group(1)}
                repos.append(current)
                continue
            m = re.match(r"^    (class|watch):\s*(\S+)\s*$", raw)
            if m and current is not None:
                current[m.group(1)] = m.group(2)
    watched = []
    for repo in repos:
        watch = overrides.get(repo["name"], {}).get("watch", repo.get("watch"))
        if watch == "issues":
            watched.append(repo["name"])
    return watched


def normalize_issue(raw: dict) -> dict | None:
    """Project an API issue onto the persisted fields; None for PRs."""
    if "pull_request" in raw:
        return None
    return {field: raw.get(field) for field in ISSUE_FIELDS}


def fetch_issues_gh(repo: str) -> list[dict]:
    """Fetch all issues for a repo via `gh api --paginate` (read-only)."""
    try:
        out = subprocess.run(
            ["gh", "api", "--paginate",
             f"repos/{repo}/issues?state=all&per_page=100"],
            capture_output=True, text=True, timeout=300,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        raise FetchError(f"gh invocation failed: {exc}") from exc
    if out.returncode != 0:
        detail = (out.stderr or out.stdout).strip().splitlines()
        raise FetchError(f"gh api failed for {repo}: "
                         f"{detail[0] if detail else 'unknown error'}")
    try:
        pages = json.loads(out.stdout)
    except ValueError as exc:
        raise FetchError(f"unparseable gh api output for {repo}") from exc
    # --paginate concatenates page arrays into one JSON array per page
    # stream; gh emits a single merged array for JSON endpoints.
    if isinstance(pages, dict):
        pages = [pages]
    issues = []
    for item in pages:
        normalized = normalize_issue(item)
        if normalized is not None:
            issues.append(normalized)
    return issues


def load_fixture(path: Path) -> dict:
    return json.loads(path.read_text())


def fetch_issues_fixture(repo: str, fixture: dict) -> list[dict]:
    entry = fixture.get(repo)
    if entry is None:
        raise FetchError(f"repo {repo} absent from fixture")
    if isinstance(entry, dict) and "error" in entry:
        raise FetchError(str(entry["error"]))
    issues = []
    for item in entry:
        normalized = normalize_issue(item)
        if normalized is not None:
            issues.append(normalized)
    return issues


def diff_repo(prior: dict | None, current: list[dict]) -> dict:
    """Diff one repo's fetched issues against its persisted state.

    `prior` is the persisted {number-as-str: issue} mapping, or None
    when the repo has never been baselined.
    """
    current_by_number = {str(i["number"]): i for i in current}
    if prior is None:
        return {"baseline": True, "state": current_by_number,
                "counts": {"open": sum(1 for i in current if i["state"] == "open"),
                           "closed": sum(1 for i in current if i["state"] == "closed"),
                           "total": len(current)},
                "new": [], "closed": [], "reopened": [], "changed": []}
    new, closed, reopened, changed = [], [], [], []
    for number, issue in current_by_number.items():
        old = prior.get(number)
        if old is None:
            new.append(issue)
        elif old["state"] == "open" and issue["state"] == "closed":
            closed.append(issue)
        elif old["state"] == "closed" and issue["state"] == "open":
            reopened.append(issue)
        elif (old["title"] != issue["title"]
              or old["updated_at"] != issue["updated_at"]
              or old["state"] != issue["state"]):
            changed.append(issue)
    return {"baseline": False, "state": current_by_number,
            "counts": None, "new": new, "closed": closed,
            "reopened": reopened, "changed": changed}


def run_check(inventory_text: str, state: dict, fetch, now: str) -> tuple[dict, list[str], bool]:
    """Run one check over all watched repos.

    Returns (new_state, report_lines, had_error). Pure apart from the
    injected `fetch` callable, so tests drive it with fixtures.
    """
    repos = parse_inventory(inventory_text)
    prior_repos = state.get("repos", {})
    new_repos = dict(prior_repos)
    lines = [f"# Repo-universe issue check — {now}", ""]
    had_error = False
    total_delta = 0
    for repo in repos:
        try:
            issues = fetch(repo)
        except FetchError as exc:
            had_error = True
            lines.append(f"## {repo}")
            lines.append(f"- ERROR: fetch failed: {exc}")
            lines.append("")
            continue
        prior_entry = prior_repos.get(repo)
        result = diff_repo(prior_entry["issues"] if prior_entry else None, issues)
        entry = {"watermark": max((i["updated_at"] or "" for i in issues), default=None),
                 "issues": result["state"]}
        if prior_entry and prior_entry.get("issues") == result["state"]:
            entry["watermark"] = prior_entry.get("watermark")
        new_repos[repo] = entry
        lines.append(f"## {repo}")
        if result["baseline"]:
            c = result["counts"]
            lines.append(f"- baseline: {c['total']} issues recorded "
                         f"({c['open']} open, {c['closed']} closed); "
                         f"history not listed as new")
        else:
            delta = (result["new"] + result["closed"]
                     + result["reopened"] + result["changed"])
            total_delta += len(delta)
            if not delta:
                lines.append("- no changes")
            for label, group in (("new", result["new"]), ("closed", result["closed"]),
                                 ("reopened", result["reopened"]),
                                 ("changed", result["changed"])):
                for issue in sorted(group, key=lambda i: i["number"]):
                    lines.append(f"- {label}: #{issue['number']} {issue['title']} "
                                 f"({issue['html_url']})")
        lines.append("")
    lines.insert(2, f"Repos checked: {len(repos)}; issues changed: {total_delta}; "
                    f"errors: {'yes' if had_error else 'no'}")
    new_state = {"version": 1, "last_run": now, "repos": new_repos}
    return new_state, lines, had_error


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--inventory", default="doc/fleet/repo-universe.yaml")
    parser.add_argument("--state-dir",
                        default="~/.local/state/repo-universe-issue-checker")
    parser.add_argument("--fixture", help="JSON fixture replacing GitHub fetches")
    parser.add_argument("--now", help="ISO-8601 run timestamp (default: now, UTC)")
    args = parser.parse_args(argv)

    now = args.now or datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    state_dir = Path(args.state_dir).expanduser()
    state_dir.mkdir(parents=True, exist_ok=True)
    state_path = state_dir / "state.json"
    state = (json.loads(state_path.read_text())
             if state_path.exists() else {"version": 1, "repos": {}})
    inventory_text = Path(args.inventory).read_text()

    if args.fixture:
        fixture = load_fixture(Path(args.fixture))
        fetch = lambda repo: fetch_issues_fixture(repo, fixture)  # noqa: E731
    else:
        fetch = fetch_issues_gh

    new_state, lines, had_error = run_check(inventory_text, state, fetch, now)

    date = now[:10]
    report_path = state_dir / f"report-{date}.md"
    suffix = 1
    while report_path.exists():
        suffix += 1
        report_path = state_dir / f"report-{date}-{suffix}.md"
    report_path.write_text("\n".join(lines) + "\n")
    state_path.write_text(json.dumps(new_state, indent=1, sort_keys=True) + "\n")
    print(f"report: {report_path}")
    print(f"state: {state_path}")
    return 1 if had_error else 0


if __name__ == "__main__":
    sys.exit(main())
