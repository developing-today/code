package codegen

// Python is the second codegen target (#1917, Approach C): the same namespace
// model that renders the TypeScript client renders a stdlib-only Python client
// with the same call surface — one typed method per tool, the same POST to
// /v1/call, the same MCPX_ENDPOINT / MCPX_SOCKET / MCPX_SESSION resolution and
// the same result unwrapping.
//
// The language dimension came first (language.go); this file is the entry that
// proves the dimension carries a second target without touching the first.

