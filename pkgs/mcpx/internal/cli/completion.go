package cli

import (
	"fmt"
	"sort"
	"strings"

	"github.com/developing-today/code/pkgs/mcpx/internal/settings"
)

// Completion renders a shell completion script.
//
// Generated from the command table and the setting registry, so a new flag is
// completable the moment it is declared. Hand-written completions are the
// first thing to rot, because nothing fails when they are wrong -- they
// simply stop being helpful, silently.
func Completion(shell, version string) (string, error) {
	cmds := Commands()
	sch, err := settings.New(settings.Registry())
	if err != nil {
		return "", err
	}

	names := make([]string, 0, len(cmds))
	for _, c := range cmds {
		names = append(names, c.Name)
		names = append(names, c.Aliases...)
	}
	sort.Strings(names)

	switch shell {
	case "bash":
		return bashCompletion(cmds, sch, names, version), nil
	case "zsh":
		return zshCompletion(cmds, sch, version), nil
	case "fish":
		return fishCompletion(cmds, sch, version), nil
	}
	return "", fmt.Errorf("no completion for %q; bash, zsh and fish are available", shell)
}

// spellings is every name a command answers to: its canonical Name
// plus its Aliases. Completion must key on all of them (#1661): the
// word-1 lists already offer aliases, so an arm keyed on the canonical
// name alone offers the alias and then refuses its flags.
func spellings(c Command) []string {
	out := make([]string, 0, len(c.Aliases)+1)
	out = append(out, c.Name)
	out = append(out, c.Aliases...)
	return out
}

func flagsFor(sch *settings.Schema, cmd string) []settings.Setting {
	var out []settings.Setting
	for _, s := range sch.ForCommand(cmd) {
		if s.Plumbing {
			// Completable only when explicitly typed. Offering internals in
			// a tab list is how someone sets one by accident.
			continue
		}
		out = append(out, s)
	}
	return out
}

func bashCompletion(cmds []Command, sch *settings.Schema, names []string, version string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# mcpx %s bash completion, generated by `mcpx completion bash`.\n", version)
	b.WriteString("_mcpx() {\n")
	b.WriteString("  local cur prev cmd\n")
	b.WriteString(`  cur="${COMP_WORDS[COMP_CWORD]}"` + "\n")
	b.WriteString(`  prev="${COMP_WORDS[COMP_CWORD-1]}"` + "\n")
	b.WriteString(`  cmd="${COMP_WORDS[1]}"` + "\n\n")
	fmt.Fprintf(&b, "  local commands=%q\n", strings.Join(names, " "))
	b.WriteString("  if [ \"$COMP_CWORD\" -eq 1 ]; then\n")
	b.WriteString("    COMPREPLY=( $(compgen -W \"$commands\" -- \"$cur\") )\n")
	b.WriteString("    return\n  fi\n\n")

	b.WriteString("  case \"$cmd\" in\n")
	for _, c := range cmds {
		var flags []string
		for _, s := range flagsFor(sch, c.Name) {
			flags = append(flags, "--"+s.FlagName())
			for _, a := range s.FlagAliases {
				flags = append(flags, "--"+a)
			}
		}
		for _, n := range handFlagNames(c.Name) {
			flags = append(flags, "--"+n)
		}
		sort.Strings(flags)
		fmt.Fprintf(&b, "    %s) COMPREPLY=( $(compgen -W %q -- \"$cur\") ) ;;\n",
			strings.Join(spellings(c), "|"), strings.Join(flags, " "))
	}
	b.WriteString("  esac\n}\n")
	b.WriteString("complete -o default -F _mcpx mcpx\n")
	return b.String()
}

func zshCompletion(cmds []Command, sch *settings.Schema, version string) string {
	var b strings.Builder
	b.WriteString("#compdef mcpx\n")
	fmt.Fprintf(&b, "# mcpx %s, generated by `mcpx completion zsh`.\n\n", version)
	b.WriteString("_mcpx() {\n  local -a commands\n  commands=(\n")
	for _, c := range cmds {
		// Quote each entry: summaries carry apostrophes, parens and glob
		// brackets (issue #272), none of which survive unquoted.
		fmt.Fprintf(&b, "    '%s:%s'\n", c.Name, zshDescribe(c.Summary))
	}
	b.WriteString("  )\n\n")
	b.WriteString("  if (( CURRENT == 2 )); then\n")
	b.WriteString("    _describe -t commands 'mcpx command' commands\n")
	b.WriteString("    return\n  fi\n\n")
	b.WriteString("  case \"${words[2]}\" in\n")
	for _, c := range cmds {
		fmt.Fprintf(&b, "    %s)\n      _arguments \\\n", strings.Join(spellings(c), "|"))
		emitted := map[string]bool{}
		for _, s := range flagsFor(sch, c.Name) {
			emitted[s.FlagName()] = true
			// The description is carried into the completion, so the shell
			// explains a flag at the point of typing it rather than sending
			// the reader to --help.
			if len(s.Enum) > 0 {
				fmt.Fprintf(&b, "        '--%s=[%s]:value:(%s)' \\\n",
					s.FlagName(), zshEscape(s.Short), strings.Join(s.Enum, " "))
				continue
			}
			if s.Kind == settings.KindBool {
				fmt.Fprintf(&b, "        '--%s[%s]' \\\n", s.FlagName(), zshEscape(s.Short))
				continue
			}
			fmt.Fprintf(&b, "        '--%s=[%s]:value:_files' \\\n",
				s.FlagName(), zshEscape(s.Short))
		}
		for _, g := range handFlagGroups(c.Name) {
			for _, f := range g.Flags {
				if emitted[f.Name] {
					continue
				}
				emitted[f.Name] = true
				fmt.Fprintf(&b, "        '--%s[%s]' \\\n", f.Name, zshEscape(f.Usage))
			}
		}
		b.WriteString("        '*:file:_files'\n      ;;\n")
	}
	b.WriteString("  esac\n}\n\n_mcpx \"$@\"\n")
	return b.String()
}

func fishCompletion(cmds []Command, sch *settings.Schema, version string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# mcpx %s, generated by `mcpx completion fish`.\n", version)
	b.WriteString("complete -c mcpx -f\n")
	for _, c := range cmds {
		for _, name := range spellings(c) {
			fmt.Fprintf(&b, "complete -c mcpx -n __fish_use_subcommand -a %s -d %s\n",
				name, fishQuote(c.Summary))
		}
	}
	for _, c := range cmds {
		seen := strings.Join(spellings(c), " ")
		for _, s := range flagsFor(sch, c.Name) {
			line := fmt.Sprintf("complete -c mcpx -n '__fish_seen_subcommand_from %s' -l %s -d %s",
				seen, s.FlagName(), fishQuote(s.Short))
			if len(s.Enum) > 0 {
				line += fmt.Sprintf(" -a %s", fishQuote(strings.Join(s.Enum, " ")))
			}
			if s.Kind != settings.KindBool {
				line += " -r"
			}
			b.WriteString(line + "\n")
		}
		for _, g := range handFlagGroups(c.Name) {
			for _, f := range g.Flags {
				fmt.Fprintf(&b, "complete -c mcpx -n '__fish_seen_subcommand_from %s' -l %s -d %s\n",
					seen, f.Name, fishQuote(f.Usage))
			}
		}
	}
	return b.String()
}

func zshEscape(s string) string {
	s = strings.ReplaceAll(s, `'`, `'\''`)
	s = strings.ReplaceAll(s, "[", `\[`)
	s = strings.ReplaceAll(s, "]", `\]`)
	s = strings.ReplaceAll(s, ":", `\:`)
	return s
}

// zshDescribe prepares a _describe entry's description. The whole entry is
// emitted single-quoted, so the shell itself needs no escaping; what remains
// is _describe's own syntax, where a colon in the description must be
// backslash-escaped so it is not read as another name separator.
func zshDescribe(s string) string {
	s = strings.ReplaceAll(s, ":", `\:`)
	s = strings.ReplaceAll(s, `'`, `'\''`)
	return s
}

func fishQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `\'`) + "'"
}
