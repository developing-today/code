import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const ctx=vm.createContext({document:{addEventListener(){}}});
vm.runInContext(fs.readFileSync('public/variants.js','utf8'),ctx);
let counter=0;ctx.nextId=()=>`new-${++counter}`;
ctx.state={items:[{id:'a',name:'A',parent:'',tags:[],notes:'keep'},{id:'b',name:'B',parent:'',tags:[]},{id:'c',name:'C',parent:'',tags:[]}]};
const run=s=>JSON.parse(vm.runInContext('JSON.stringify('+s+')',ctx));
const first=run("variantPlan(state,['a','b','c'],{action:'group',name:'Options'},nextId)");
assert.equal(first.groupIds.length,1);const original=first.groupIds[0];
assert.equal(ctx.state.items[0].notes,'keep');assert.equal(ctx.state.items[0].parent,original);
const family=ctx.state.items[0].variantFamilyIds.slice();
const split=run("variantPlan(state,['a','b','c'],{action:'split',labels:{a:'Set one',b:'Set one'}},nextId)");
assert.equal(split.groupIds.length,1);assert.equal(ctx.state.items[0].parent,ctx.state.items[1].parent);assert.equal(ctx.state.items[2].parent,'');
assert.ok(family.every(x=>ctx.state.items[2].variantFamilyIds.includes(x)));
assert.equal(ctx.state.items.filter(x=>['a','b','c'].includes(x.id)).length,3);
run("variantPlan(state,['a'],{action:'detach'},nextId)");assert.equal(ctx.state.items[0].parent,'');
run(`variantPlan(state,['a'],{action:'group',target:'${original}'},nextId)`);assert.equal(ctx.state.items[0].parent,original);
let snapshot=JSON.stringify(ctx.state);
assert.throws(()=>run(`variantPlan(state,['${original}'],{action:'group',target:'${original}'},nextId)`),/inside itself/);
assert.equal(JSON.stringify(ctx.state),snapshot);
assert.throws(()=>run(`variantPlan(state,['${original}','a'],{action:'detach'},nextId)`),/either a group/);
assert.throws(()=>run("variantPlan(state,['missing'],{action:'detach'},nextId)"),/existing items/);
assert.throws(()=>run("variantPlan(state,['a'],{action:'group',target:'b'},nextId)"),/active general item/);
assert.equal(JSON.stringify(ctx.state),snapshot);
console.log('PASS variants: stable IDs, grouping, splits, standalone options, retained family associations, cycle and mixed-level rejection.');
// Failed allocation is atomic, even after a generated group or family was staged.
snapshot=JSON.stringify(ctx.state);ctx.badId=()=>ctx.state.items[0].id;
assert.throws(()=>run("variantPlan(state,['a'],{action:'group',name:'New'},badId)"),/allocation/);
assert.equal(JSON.stringify(ctx.state),snapshot);
assert.throws(()=>run("variantPlan(state,['a'],{action:'group',name:'B'},nextId)"),/name already/);
assert.equal(JSON.stringify(ctx.state),snapshot);
run(`variantPlan(state,['a'],{action:'detach',destinationParent:'${original}'},nextId)`);
assert.equal(ctx.state.items[0].parent,original);
console.log('PASS variant atomicity, duplicate-name confirmation and nested destinations.');
