assert.ok(Object.isFrozen(principalFromGateway(h({'oai-authenticated-user-id':'acct_1'}))));
for(const id of ['','a b','a\u200bb','x'.repeat(101)])assert.equal(principalFromGateway(h(id?{'oai-authenticated-user-id':id}:{})),null);
