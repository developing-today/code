import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const ctx=vm.createContext({document:{addEventListener(){}},console});
vm.runInContext(fs.readFileSync('public/steering.js','utf8'),ctx);
const run=c=>vm.runInContext(c,ctx);
run(`s={items:[{id:'a',name:'A',priority:2},{id:'b',name:'B'}]}; r={id:'r',revision:1,status:'pending',targets:steeringTargets(s,['a','a'])};s.steering=[r];`);
assert.equal(run('r.targets.length'),1);
assert.throws(()=>run("steeringPatch({id:'bad'})"),/Unsupported/);
assert.throws(()=>run('steeringPatch({priority:101})'),/Priority/);
assert.throws(()=>run('steeringPatch({priority:0.5})'),/Priority/);
assert.throws(()=>run("steeringPatch({state:'unknown'})"),/state/);
assert.throws(()=>run("steeringApplyToState(s,'r',2,{priority:90},'now')"),/version/);
run("s.items[0].name='changed'");
assert.throws(()=>run("steeringApplyToState(s,'r',1,{priority:90},'now')"),/changed since/);
run("s.items[0].name='A';steeringApplyToState(s,'r',1,{priority:90},'now')");
assert.equal(run('s.items[0].id'),'a');assert.equal(run('s.items[0].priority'),90);assert.equal(run('s.items[1].priority'),undefined);
assert.equal(run('r.revision'),2);assert.equal(run('r.status'),'applied');
assert.throws(()=>run("steeringApplyToState(s,'r',2,{priority:90},'now')"),/no longer pending/);
run("s.steering.push({id:'general',revision:1,status:'pending',targets:[]})");
assert.throws(()=>run("steeringApplyToState(s,'general',1,{priority:20},'now')"),/General/);
assert.equal(run('steeringJob(r).delivery'),'manual export; not sent');
run('job=steeringJob(r);job.request.targets[0].before.name="modified"');
assert.equal(run('r.targets[0].before.name'),'A');
console.log('PASS steering: stable targets, dedupe, strict patches, stale/revision guards, terminal lifecycle, general-request isolation, portable manual export.');
ctx.uid=()=> 'command-id';ctx.steeringCommand=c=>{ctx.sent=c};run("steeringSubmit({action:'create',requestId:'new',text:'hello'})");assert.equal(ctx.sent.commandId,'command-id');assert.equal(ctx.sent.action,'create');

let reportSubmit;ctx.editable=()=>true;ctx.active={id:'store'};ctx.e=x=>String(x);ctx.area=()=>'';ctx.prose=x=>String(x??'');ctx.dlg=(title,body,fn)=>{reportSubmit=fn};run("steeringEditor(['spend'],'report')");reportSubmit({request:'Explain this report'});assert.equal(ctx.sent.targets[0].kind,'report');assert.equal(ctx.sent.targets[0].id,'spend');
