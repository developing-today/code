//! The conversion executor: pre-flight, write-ahead intent, linked
//! batch submission.
//!
//! A conversion is the composed pair from the TigerBeetle Currency
//! Exchange recipe (see the #2040 investigation): T1 moves the source
//! amount from the user to the liquidity provider (LP) on the source
//! ledger, an optional fee leg moves the fee from the user to the fee
//! account on the source ledger, and T3 moves the converted amount
//! from the LP to the user on the destination ledger. All legs are
//! stamped `user_data_128 = conversion_id` and submitted as ONE linked
//! batch, so either every leg posts or none does.
//!
//! Cross-ledger transfers do not exist in TigerBeetle; the exchange
//! rate and its authorisation are control-plane data (#2063), carried
//! here as a [`RateQuote`] and recorded on the intent record.

use anyhow::{Context, Result, bail};

use super::intent::{IntentRecord, IntentState, IntentStore};
use super::ledger::{AccountId, LedgerBackend, Transfer, TransferError};

/// Transfer `code` for conversion legs (chart-of-accounts, #2063).
pub const TRANSFER_CODE_CONVERSION: u16 = 1;

/// An authorised rate: `amount_out = amount_in * numerator / denominator`,
/// rounded down — in the LP's favour, per the Currency Exchange recipe.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RateQuote {
    pub numerator: u128,
    pub denominator: u128,
    pub authorisation_id: String,
}

impl RateQuote {
    pub fn amount_out(&self, amount_in: u128) -> u128 {
        amount_in.saturating_mul(self.numerator) / self.denominator
    }
}

/// Everything needed to execute one conversion. Accounts are stub
/// TigerBeetle accounts created by the caller (the PoC sanctions stub
/// accounts; real account/LP representation comes from #2062).
#[derive(Clone, Debug)]
pub struct ConversionRequest {
    pub conversion_id: u128,
    /// Pre-generated transfer IDs, one per leg, in leg order
    /// (T1, fee leg if any, T3). Generated by the caller and persisted
    /// on the intent record before submission.
    pub transfer_ids: Vec<u128>,
    pub user_source: AccountId,
    pub lp_source: AccountId,
    pub fee_account: Option<AccountId>,
    pub lp_dest: AccountId,
    pub user_dest: AccountId,
    pub source_ledger: u32,
    pub dest_ledger: u32,
    pub amount_in: u128,
    /// Fee taken on the source ledger; 0 means no fee leg.
    pub fee_amount: u128,
    pub quote: RateQuote,
}

/// Executes conversions against a [`LedgerBackend`], writing intent
/// records to an [`IntentStore`] ahead of every submission.
pub struct ConversionExecutor<B: LedgerBackend, S: IntentStore> {
    pub backend: B,
    pub store: S,
}

impl<B: LedgerBackend, S: IntentStore> ConversionExecutor<B, S> {
    pub fn new(backend: B, store: S) -> Self {
        Self { backend, store }
    }

    /// Build the legs for a request. Every leg but the last is
    /// `linked`; the batch is submitted as one chain.
    pub fn build_legs(request: &ConversionRequest) -> Result<Vec<Transfer>> {
        let amount_out = request.quote.amount_out(request.amount_in);
        let mut legs = Vec::with_capacity(3);
        let mut ids = request.transfer_ids.iter();
        let mut next_id = move || -> Result<u128> {
            ids.next()
                .copied()
                .context("transfer_ids must cover every leg (T1, fee, T3)")
        };
        legs.push(Transfer {
            id: next_id()?,
            debit_account_id: request.user_source,
            credit_account_id: request.lp_source,
            amount: request.amount_in,
            ledger: request.source_ledger,
            user_data_128: request.conversion_id,
            code: TRANSFER_CODE_CONVERSION,
            linked: true,
        });
        if request.fee_amount > 0 {
            legs.push(Transfer {
                id: next_id()?,
                debit_account_id: request.user_source,
                credit_account_id: request
                    .fee_account
                    .context("fee_amount > 0 requires a fee_account")?,
                amount: request.fee_amount,
                ledger: request.source_ledger,
                user_data_128: request.conversion_id,
                code: TRANSFER_CODE_CONVERSION,
                linked: true,
            });
        }
        legs.push(Transfer {
            id: next_id()?,
            debit_account_id: request.lp_dest,
            credit_account_id: request.user_dest,
            amount: amount_out,
            ledger: request.dest_ledger,
            user_data_128: request.conversion_id,
            code: TRANSFER_CODE_CONVERSION,
            linked: false,
        });
        Ok(legs)
    }

    /// Pre-flight (§4 of #2063): every account exists on the right
    /// ledger, the user can cover amount + fee, and the LP holds
    /// enough destination inventory. Failing here means no intent is
    /// written and nothing is submitted.
    pub fn preflight(&self, request: &ConversionRequest) -> Result<()> {
        let amount_out = request.quote.amount_out(request.amount_in);
        if request.quote.denominator == 0 {
            bail!("preflight: rate quote has a zero denominator");
        }
        if amount_out == 0 {
            bail!("preflight: rate quote produces a zero destination amount");
        }
        let check_account = |id: AccountId, ledger: u32, role: &str| -> Result<()> {
            let account = self
                .backend
                .lookup_account(id)
                .with_context(|| format!("preflight: {role} account {id} does not exist"))?;
            if account.ledger != ledger {
                bail!(
                    "preflight: {role} account {id} is on ledger {}, expected {ledger}",
                    account.ledger
                );
            }
            Ok(())
        };
        check_account(request.user_source, request.source_ledger, "user source")?;
        check_account(request.lp_source, request.source_ledger, "LP source")?;
        if let Some(fee_account) = request.fee_account {
            check_account(fee_account, request.source_ledger, "fee")?;
        }
        check_account(request.lp_dest, request.dest_ledger, "LP destination")?;
        check_account(request.user_dest, request.dest_ledger, "user destination")?;

        let user_balance = self
            .backend
            .account_balance(request.user_source)
            .context("preflight: user source balance missing")?;
        let needed = request
            .amount_in
            .checked_add(request.fee_amount)
            .context("preflight: amount + fee overflow")?;
        if user_balance.spendable() < needed {
            bail!(
                "preflight: user source spendable {} < amount + fee {needed}",
                user_balance.spendable()
            );
        }
        let lp_balance = self
            .backend
            .account_balance(request.lp_dest)
            .context("preflight: LP destination balance missing")?;
        if lp_balance.spendable() < amount_out {
            bail!(
                "preflight: insufficient LP inventory — LP destination spendable {} < amount_out {amount_out}",
                lp_balance.spendable()
            );
        }
        Ok(())
    }

    /// Write-ahead phase: pre-flight, build the legs, and persist the
    /// intent record (state `Recorded`) BEFORE any submission. Kept
    /// separate from [`Self::submit`] so the crash window between
    /// intent and submission is directly testable.
    pub fn prepare(&mut self, request: &ConversionRequest) -> Result<IntentRecord> {
        self.preflight(request)?;
        let legs = Self::build_legs(request)?;
        let record = IntentRecord {
            conversion_id: request.conversion_id,
            legs,
            user_source: request.user_source,
            lp_source: request.lp_source,
            fee_account: request.fee_account,
            lp_dest: request.lp_dest,
            user_dest: request.user_dest,
            source_ledger: request.source_ledger,
            dest_ledger: request.dest_ledger,
            amount_in: request.amount_in,
            amount_out: request.quote.amount_out(request.amount_in),
            fee_amount: request.fee_amount,
            authorisation_id: request.quote.authorisation_id.clone(),
            state: IntentState::Recorded,
        };
        self.store
            .put(&record)
            .context("write-ahead intent persist failed")?;
        Ok(record)
    }

    /// Submission phase: mark the record `Submitted` (still ahead of
    /// the ledger call), submit the linked batch, then mark `Posted`.
    /// A crash between the ledger call and the `Posted` write leaves a
    /// `Submitted` record the recovery scanner reconciles by lookup —
    /// it never resubmits blindly, and idempotent IDs make even a
    /// resubmission safe.
    pub fn submit(&mut self, record: &mut IntentRecord) -> Result<()> {
        record.state = IntentState::Submitted;
        self.store
            .put(record)
            .context("intent state persist (Submitted) failed")?;
        let results = self.backend.create_transfers(&record.legs);
        for (leg, result) in record.legs.iter().zip(results.iter()) {
            match result {
                Ok(()) | Err(TransferError::Exists) => {}
                Err(error) => {
                    bail!(
                        "conversion {} leg {} failed: {error:?}",
                        record.conversion_id,
                        leg.id
                    );
                }
            }
        }
        record.state = IntentState::Posted;
        self.store
            .put(record)
            .context("intent state persist (Posted) failed")?;
        Ok(())
    }

    /// The normal path: prepare (write-ahead) then submit.
    pub fn execute(&mut self, request: &ConversionRequest) -> Result<IntentRecord> {
        let mut record = self.prepare(request)?;
        self.submit(&mut record)?;
        Ok(record)
    }
}
