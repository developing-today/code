/** Regenerate the checked-in compatibility corpus from the actual editor schemas. */
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { Node } from "prosemirror-model";
import { Transform } from "prosemirror-transform";
import { rawSchema, richSchema } from "../editor";

const schemaByMode = { rich: richSchema, raw: rawSchema } as const;

function generated(mode: keyof typeof schemaByMode, baseJSON: unknown, edits: (tr: Transform) => void) {
  const schema = schemaByMode[mode];
  const base = Node.fromJSON(schema, baseJSON);
  const transform = new Transform(base);
  edits(transform);
  return {
    mode,
    base: base.toJSON(),
    steps: transform.steps.map((step) => step.toJSON()),
    accepted: true,
    final: transform.doc.toJSON(),
  };
}

const richBase = { type: "doc", content: [{ type: "paragraph", content: [{ type: "text", text: "hello" }] }] };
const rawBase = { type: "doc", content: [{ type: "code_block", attrs: { language: "txt" }, content: [{ type: "text", text: "hello" }] }] };

const cases = [
  generated("rich", richBase, (tr) => {
    tr.insert(6, richSchema.text("!")).insert(7, richSchema.text("?"));
  }),
  generated("raw", rawBase, (tr) => {
    tr.insert(6, rawSchema.text("!")).insert(7, rawSchema.text("?"));
  }),
  {
    mode: "rich",
    base: richBase,
    steps: [{ stepType: "not-a-prosemirror-step", from: 1, to: 1 }],
    accepted: false,
    rejection: "unknown-step-type",
  },
  {
    mode: "rich",
    base: richBase,
    steps: [{ stepType: "replace", from: 6, to: 6, slice: { content: [{ type: "not-a-schema-node" }] } }],
    accepted: false,
    rejection: "unknown-node-in-slice",
  },
  {
    mode: "rich",
    base: richBase,
    steps: [{ stepType: "replace", from: 99, to: 99, slice: { content: [{ type: "text", text: "x" }] } }],
    accepted: false,
    rejection: "out-of-range-position",
  },
  {
    mode: "rich",
    base: richBase,
    steps: ["not-an-object"],
    accepted: false,
    rejection: "non-object-step",
  },
];

const output = {
  format: "prosemirror-step-corpus/v1",
  source: "Generated by generate-prosemirror-step-fixtures.ts from editor.ts schemas and prosemirror-transform.",
  cases,
};
const outputPath = resolve(import.meta.dirname, "prosemirror-step-corpus.json");
const serialized = `${JSON.stringify(output, null, 2)}\n`;
if (process.argv.includes("--check")) {
  const checkedIn = await readFile(outputPath, "utf8");
  if (checkedIn !== serialized) {
    console.error("ProseMirror fixture corpus is stale; rerun without --check.");
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, serialized);
}
