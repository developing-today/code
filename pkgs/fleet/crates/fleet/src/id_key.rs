//! The `fleet id` domain, build slice 1 of design #10391 (pass 2,
//! §5 slice 1; issue #15430): the iroh session key lifecycle and
//! stamping from design §4.1. No iroh dial yet — slices 2–4
//! (#15434, #15435, #15436) build the proxy and initiator on this
//! key, and slice 5 (#15399) serves over it.
//!
//! The contract this module implements, from §4.1:
//!
//! - **Default: one ephemeral ed25519 node key per session**,
//!   generated from the OS RNG at session start. Never hardcoded,
//!   checked in, or logged.
//! - **Caller override:** `--id-secret` / `FLEET_ID_SECRET` supplies
//!   the 32-byte secret (hex); fleet uses it verbatim and never
//!   persists it.
//! - **Stamping:** the public key (NodeId) travels everywhere the
//!   #10357 context stamp travels: as `fleet_node_id` on the queue
//!   stamp ([`SessionKey::stamp_json`]) and as `FLEET_ID_NODE_ID`
//!   in the dot-sourced session env. The secret is exported ONLY as
//!   `FLEET_ID_SECRET` in that same in-session env rendering — it is
//!   never in the stamp, and this module has no log/trip-record
//!   rendering that could carry it.
//! - **Storage:** process memory only, in a [`Zeroizing`] buffer;
//!   session end (drop, or an explicit [`SessionKey::end_session`])
//!   zeroizes it. No disk write, no secret-store write.
//! - **Rotation/disposal:** keys are single-session; rotation is a
//!   new session. Nothing is published beyond ticket holders, so
//!   there is no revocation protocol.
//!
//! The oracle for the NodeId derivation is `ed25519-dalek`'s
//! `SigningKey` — the same key type iroh's `SecretKey` wraps, so a
//! NodeId minted here is the NodeId iroh will present for the same
//! secret in slices 2–4.

use zeroize::{Zeroize, Zeroizing};

/// Env name carrying the session NodeId in the dot-sourced stamp env.
pub const NODE_ID_ENV: &str = "FLEET_ID_NODE_ID";
/// Env name carrying the session secret — in-session env only.
pub const SECRET_ENV: &str = "FLEET_ID_SECRET";
/// The queue-stamp field name for the session NodeId (§4.7).
pub const STAMP_FIELD: &str = "fleet_node_id";

/// Where a session key came from (§4.1: generated by default, or
/// supplied verbatim by the caller).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeySource {
    Ephemeral,
    CallerSupplied,
}

/// A session's iroh keypair: the 32-byte ed25519 secret, held in a
/// zeroizing buffer, and its derived NodeId (the public key).
/// Constructing one is the session-start act of §4.1; dropping it
/// is the session-end act (the secret is zeroized either way).
pub struct SessionKey {
    secret: Zeroizing<[u8; 32]>,
    node_id: [u8; 32],
    source: KeySource,
}

/// Why a caller-supplied secret was rejected.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum KeyError {
    /// Not exactly 64 hex characters (a 32-byte secret).
    BadSecretForm,
    /// The OS RNG refused to fill the ephemeral secret.
    RngUnavailable,
}

impl std::fmt::Display for KeyError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            KeyError::BadSecretForm => f.write_str("secret must be 64 hex characters (32 bytes)"),
            KeyError::RngUnavailable => f.write_str("OS RNG unavailable"),
        }
    }
}

impl std::error::Error for KeyError {}

fn derive_node_id(secret: &[u8; 32]) -> [u8; 32] {
    ed25519_dalek::SigningKey::from_bytes(secret)
        .verifying_key()
        .to_bytes()
}

impl SessionKey {
    /// Session start, default path: a fresh ephemeral key from the
    /// OS RNG (§4.1). Two calls never share a key in practice; the
    /// freshness property is test-covered.
    pub fn generate() -> Result<Self, KeyError> {
        let mut secret = Zeroizing::new([0u8; 32]);
        getrandom::fill(&mut *secret).map_err(|_| KeyError::RngUnavailable)?;
        let node_id = derive_node_id(&secret);
        Ok(Self {
            secret,
            node_id,
            source: KeySource::Ephemeral,
        })
    }

    /// Session start, caller-override path: the secret is used
    /// verbatim (§4.1) — parsed from hex, never re-derived,
    /// stretched, or persisted.
    pub fn from_secret_hex(hex: &str) -> Result<Self, KeyError> {
        let secret = Zeroizing::new(parse_secret_hex(hex)?);
        let node_id = derive_node_id(&secret);
        Ok(Self {
            secret,
            node_id,
            source: KeySource::CallerSupplied,
        })
    }

    /// Resolve a session key the way the CLI does: `FLEET_ID_SECRET`
    /// when set (caller-supplied), a fresh ephemeral key otherwise.
    pub fn from_env() -> Result<Self, KeyError> {
        match std::env::var(SECRET_ENV) {
            Ok(hex) if !hex.trim().is_empty() => Self::from_secret_hex(hex.trim()),
            _ => Self::generate(),
        }
    }

    pub fn source(&self) -> KeySource {
        self.source
    }

    /// Borrow the session secret for constructing the matching iroh
    /// endpoint. Callers must not copy it into logs or persistent state.
    pub(crate) fn secret_bytes(&self) -> &[u8; 32] {
        &self.secret
    }

    /// The NodeId as 64 lowercase hex characters — the form the
    /// stamp and the env carry.
    pub fn node_id_hex(&self) -> String {
        to_hex(&self.node_id)
    }

    /// The secret as hex. Only the in-session env rendering
    /// ([`SessionKey::env_lines`]) may call this; the stamp never
    /// does.
    fn secret_hex(&self) -> String {
        to_hex(&self.secret)
    }

    /// The queue stamp fragment (§4.7): `{ "fleet_node_id": … }`.
    /// Carries the public key only — by construction there is no
    /// code path from the secret into this value.
    pub fn stamp_json(&self) -> serde_json::Value {
        serde_json::json!({ STAMP_FIELD: self.node_id_hex() })
    }

    /// The dot-sourced env rendering: `FLEET_ID_NODE_ID` always,
    /// `FLEET_ID_SECRET` alongside it. This rendering is the ONLY
    /// place the secret leaves the process, and §4.1 scopes it to
    /// the owning session's own environment.
    pub fn env_lines(&self) -> String {
        format!(
            "export {NODE_ID_ENV}={}\nexport {SECRET_ENV}={}\n",
            self.node_id_hex(),
            self.secret_hex()
        )
    }

    /// Session end: zeroize the secret now instead of waiting for
    /// drop. After this call the key must not be used; the NodeId
    /// remains readable (it is public).
    pub fn end_session(&mut self) {
        self.secret.zeroize();
    }
}

impl Drop for SessionKey {
    fn drop(&mut self) {
        self.end_session();
    }
}

fn parse_secret_hex(hex: &str) -> Result<[u8; 32], KeyError> {
    let bytes = hex.as_bytes();
    if bytes.len() != 64 {
        return Err(KeyError::BadSecretForm);
    }
    let mut out = [0u8; 32];
    for (i, pair) in bytes.chunks_exact(2).enumerate() {
        let hi = hex_nibble(pair[0])?;
        let lo = hex_nibble(pair[1])?;
        out[i] = (hi << 4) | lo;
    }
    Ok(out)
}

fn hex_nibble(b: u8) -> Result<u8, KeyError> {
    match b {
        b'0'..=b'9' => Ok(b - b'0'),
        b'a'..=b'f' => Ok(b - b'a' + 10),
        b'A'..=b'F' => Ok(b - b'A' + 10),
        _ => Err(KeyError::BadSecretForm),
    }
}

fn to_hex(bytes: &[u8; 32]) -> String {
    let mut s = String::with_capacity(64);
    for b in bytes {
        s.push(char::from_digit((b >> 4) as u32, 16).expect("nibble"));
        s.push(char::from_digit((b & 0xf) as u32, 16).expect("nibble"));
    }
    s
}

const USAGE: &str = "\
Usage: fleet id session-key [--id-secret <hex>] [--stamp | --node-id]
       fleet id proxy-mode [--raw] [--opaque] [--alpn <alpn>]
                           [--mode <1|2|3|name>]  (design §4.2, #15434)

Mint (or adopt, via --id-secret / FLEET_ID_SECRET) this session's
iroh key and render its stamp (design #10391 §4.1):

  (default)   the dot-sourced env lines: FLEET_ID_NODE_ID plus
              FLEET_ID_SECRET (in-session only)
  --stamp     the queue stamp JSON: {\"fleet_node_id\": …} — public
              key only, never the secret
  --node-id   just the NodeId hex

The key lives in process memory only and is zeroized when this
command exits; nothing is written to disk or the secret store.";

/// `fleet id session-key` — see [`USAGE`]. Returns a process exit
/// code (0 ok, 2 usage).
pub fn run(args: &[String]) -> i32 {
    let mut secret_arg: Option<String> = None;
    let mut mode = Mode::Env;
    let mut rest = args.iter();
    // args[0] is the subcommand name, routed here by main;
    // everything after it is this verb's own.
    match rest.next().map(|s| s.as_str()) {
        Some("session-key") => {}
        // Slice 2 (#15434, §4.2): mode selection lives in id_proxy.
        Some("proxy-mode") => {
            let tail: Vec<String> = rest.cloned().collect();
            return crate::id_proxy::run_proxy_mode(&tail);
        }
        Some(other) => {
            eprintln!("error: unknown 'fleet id' command '{other}'\n\n{USAGE}");
            return 2;
        }
        None => {
            eprintln!("error: 'fleet id' needs a command\n\n{USAGE}");
            return 2;
        }
    }
    while let Some(arg) = rest.next() {
        match arg.as_str() {
            "--help" | "-h" | "help" => {
                println!("{USAGE}");
                return 0;
            }
            "--stamp" => mode = Mode::Stamp,
            "--node-id" => mode = Mode::NodeId,
            "--id-secret" => match rest.next() {
                Some(v) => secret_arg = Some(v.clone()),
                None => {
                    eprintln!("error: --id-secret needs a 64-hex-character value");
                    return 2;
                }
            },
            other => {
                eprintln!("error: unknown argument '{other}'\n\n{USAGE}");
                return 2;
            }
        }
    }
    let key = match &secret_arg {
        Some(hex) => SessionKey::from_secret_hex(hex),
        None => SessionKey::from_env(),
    };
    let mut key = match key {
        Ok(k) => k,
        Err(e) => {
            eprintln!("error: {e}");
            return 2;
        }
    };
    match mode {
        Mode::Env => print!("{}", key.env_lines()),
        Mode::Stamp => println!("{}", key.stamp_json()),
        Mode::NodeId => println!("{}", key.node_id_hex()),
    }
    key.end_session();
    0
}

#[derive(Clone, Copy)]
enum Mode {
    Env,
    Stamp,
    NodeId,
}

#[cfg(test)]
mod tests {
    use super::*;
    use proptest::prelude::*;

    /// Oracle: ed25519-dalek's own derivation — the key type iroh's
    /// SecretKey wraps, so matching it is matching iroh's NodeId.
    fn oracle_node_id(secret: &[u8; 32]) -> String {
        to_hex(&derive_node_id(secret))
    }

    #[test]
    fn fresh_ephemeral_key_per_session() {
        let a = SessionKey::generate().expect("rng");
        let b = SessionKey::generate().expect("rng");
        assert_eq!(a.source(), KeySource::Ephemeral);
        assert_ne!(a.node_id_hex(), b.node_id_hex());
        assert_ne!(a.secret_hex(), b.secret_hex());
    }

    #[test]
    fn caller_supplied_key_is_used_verbatim() {
        let hex = "000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f";
        let key = SessionKey::from_secret_hex(hex).expect("parse");
        assert_eq!(key.source(), KeySource::CallerSupplied);
        assert_eq!(key.secret_hex(), hex, "secret round-trips verbatim");
        let raw: [u8; 32] = parse_secret_hex(hex).expect("parse");
        assert_eq!(key.node_id_hex(), oracle_node_id(&raw));
    }

    #[test]
    fn malformed_secrets_are_refused() {
        for bad in [
            "",
            "00",
            &"00".repeat(31),
            &"00".repeat(33),
            &"zz".repeat(32),
        ] {
            assert_eq!(
                SessionKey::from_secret_hex(bad).map(|_| ()),
                Err(KeyError::BadSecretForm),
                "input: {bad:?}"
            );
        }
    }

    #[test]
    fn stamp_carries_node_id_and_never_the_secret() {
        let key = SessionKey::generate().expect("rng");
        let stamp = key.stamp_json().to_string();
        assert!(stamp.contains(&key.node_id_hex()));
        assert!(
            !stamp.contains(&key.secret_hex()),
            "stamp leaked the secret: {stamp}"
        );
        assert!(!stamp.contains(SECRET_ENV));
    }

    #[test]
    fn env_lines_scope_the_secret_to_the_secret_line() {
        let key = SessionKey::generate().expect("rng");
        let env = key.env_lines();
        let node_line = env
            .lines()
            .find(|l| l.contains(NODE_ID_ENV))
            .expect("node id line");
        assert!(node_line.contains(&key.node_id_hex()));
        assert!(!node_line.contains(&key.secret_hex()));
        let secret_line = env
            .lines()
            .find(|l| l.contains(SECRET_ENV))
            .expect("secret line");
        assert!(secret_line.contains(&key.secret_hex()));
    }

    #[test]
    fn end_session_zeroizes_the_secret() {
        let mut key = SessionKey::generate().expect("rng");
        assert_ne!(*key.secret, [0u8; 32]);
        key.end_session();
        assert_eq!(*key.secret, [0u8; 32], "secret must be zeroized");
        // The NodeId is public and survives session end.
        assert_eq!(key.node_id_hex().len(), 64);
    }

    proptest! {
        /// Any 32-byte secret derives the dalek-oracle NodeId, and
        /// distinct secrets give distinct NodeIds (ed25519 key
        /// derivation is injective on seeds for stamp purposes).
        #[test]
        fn node_id_matches_oracle_and_is_injective(
            a in any::<[u8; 32]>(),
            b in any::<[u8; 32]>(),
        ) {
            let ka = SessionKey::from_secret_hex(&to_hex(&a)).expect("hex");
            prop_assert_eq!(ka.node_id_hex(), oracle_node_id(&a));
            prop_assert_eq!(ka.secret_hex(), to_hex(&a));
            if a != b {
                let kb = SessionKey::from_secret_hex(&to_hex(&b)).expect("hex");
                prop_assert_ne!(ka.node_id_hex(), kb.node_id_hex());
            }
        }

        /// The stamp never contains the secret, for any key.
        #[test]
        fn stamp_never_leaks_secret(secret in any::<[u8; 32]>()) {
            let key = SessionKey::from_secret_hex(&to_hex(&secret)).expect("hex");
            let stamp = key.stamp_json().to_string();
            prop_assert!(!stamp.contains(&key.secret_hex()));
        }
    }
}
