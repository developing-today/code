# Reads the RFC 8032 text (argv[1]) and writes a Rust table of its Ed25519 test vectors (argv[2]).
import re, sys
lines = open(sys.argv[1], encoding="utf-8").read().splitlines()
blocks, cur, label = {}, None, None
for line in lines:
    m = re.match(r"\s*-----TEST (.+)$", line)
    if m:
        cur = m.group(1).strip()
        blocks[cur] = {"msg_len": None}
        label = None
        continue
    if cur is None:
        continue
    s = line.strip()
    if not s:
        continue
    if s.startswith("SECRET KEY:"):
        if "sk" in blocks[cur]:  # a second SECRET KEY without a new header starts section 7.2/7.3 vectors: stop here
            cur, label = None, None
            continue
        label = "sk"
    elif s.startswith("PUBLIC KEY:"):
        label = "pk"
    elif s.startswith("MESSAGE"):
        label = "msg"
        blocks[cur]["msg_len"] = int(re.search(r"length (\d+) byte", s).group(1))
        blocks[cur].setdefault("msg", "")
    elif s.startswith("SIGNATURE:"):
        label = "sig"
    elif s.startswith("ALGORITHM:"):
        label = None
    elif label and re.fullmatch(r"[0-9a-f]+", s):
        blocks[cur][label] = blocks[cur].get(label, "") + s
out = ["// Generated by scripts/gen_rfc_vectors.py from RFC 8032 section 7.1 (rfc-editor.org/rfc/rfc8032.txt).", "pub const RFC8032: &[(&str, &str, &str, &str, &str)] = &["]
for name in ["1", "2", "3", "1024", "SHA(abc)"]:
    b = blocks[name]
    assert len(b["sk"]) == 64 and len(b["pk"]) == 64 and len(b["sig"]) == 128, name
    assert len(b.get("msg", "")) == 2 * b["msg_len"], (name, b["msg_len"])
    print(f"ok {name}: msg_len={b['msg_len']}")
    out.append(f'    ("TEST {name}", "{b["sk"]}", "{b["pk"]}", "{b.get("msg", "")}", "{b["sig"]}"),')
out.append("];")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote", sys.argv[2])
