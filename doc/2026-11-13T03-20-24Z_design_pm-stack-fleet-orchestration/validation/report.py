#!/usr/bin/env python3
"""CEN-06 — experiment report writer (#9436).

Translates the immutable CEN-05 experiment artifact (report.json,
produced by experiment.py) into a reviewable evidence report at
research/priority-exploration-experiment.md. The writer is separate
from the experiment on purpose: experiment code must not author its
own acceptance narrative.

The report separates, in order: external source facts (what the
artifact carries verbatim), measured model outputs (what the run
recorded), inference (what those outputs do and do not support), and
recommendation. A measurement the artifact does not carry is marked
missing by name — never filled in, never guessed. A synthetic
simulation is never called a production result, and no production
benefit is claimed.

Standard library only; deterministic output (no timestamps), so a
reviewer can regenerate the report from the immutable artifact and
diff it byte for byte.

Run:  python3 -I report.py [--input report.json]
                           [--output ../research/priority-exploration-experiment.md]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_INPUT = HERE / "report.json"
DEFAULT_OUTPUT = HERE.parent / "research" / "priority-exploration-experiment.md"

# The measurements a reviewable evidence report requires, and where
# each must come from in the artifact. Anything absent is reported
# missing under its name here — this list is the contract the first
# oracle test (test_report.py) pins.
REQUIRED = ("run_id", "seed", "sample_count", "oracle",
            "uncertainty", "fixture_provenance", "threshold")


def load_artifact(raw: bytes) -> dict:
    doc = json.loads(raw.decode("utf-8"))
    if not isinstance(doc, dict):
        raise ValueError("experiment artifact must be a JSON object")
    return doc


def artifact_digest(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def missing_measurements(a: dict) -> list[str]:
    """Names of required measurements the artifact does not carry."""
    inputs = a.get("inputs") or {}
    missing = []
    if not a.get("run_id"):
        missing.append("run_id")
    if inputs.get("seed") is None:
        missing.append("seed")
    if not (inputs.get("cases") and inputs.get("draws")):
        missing.append("sample_count")
    counts = (a.get("counts") or {}).get("by_oracle") or {}
    if not (a.get("oracles") and counts):
        missing.append("oracle")
    stats = a.get("statistics") or {}
    if not (stats.get("absolute_bounds") and a.get("max_errors")):
        missing.append("uncertainty")
    if not inputs.get("fixture_sha256"):
        missing.append("fixture_provenance")
    if not a.get("tolerances"):
        missing.append("threshold")
    return missing


def render_report(a: dict, digest: str) -> str:
    inputs = a.get("inputs") or {}
    counts = (a.get("counts") or {}).get("by_oracle") or {}
    missing = missing_measurements(a)
    lines = []
    lines.append("# Priority exploration experiment — evidence report (CEN-06)")
    lines.append("")
    lines.append("Generated by `validation/report.py` from the immutable CEN-05")
    lines.append("artifact `validation/report.json`. Regenerate and diff to review:")
    lines.append("")
    lines.append("    python3 -I validation/report.py")
    lines.append("")
    lines.append(f"- Artifact schema: `{a.get('schema', 'unknown')}`")
    lines.append(f"- Artifact SHA-256 (result digest): `{digest}`")
    lines.append(f"- Run ID: `{a.get('run_id', 'MISSING — see Missing measurements')}`")
    lines.append("")
    lines.append("## External source facts")
    lines.append("")
    lines.append("Verbatim from the artifact; the writer adds nothing here.")
    lines.append("")
    lines.append(f"- Fixture SHA-256 (provenance): `{inputs.get('fixture_sha256', 'MISSING')}`")
    runtime = a.get("runtime") or {}
    lines.append(f"- PRNG: {runtime.get('prng', 'MISSING')}")
    for limit in a.get("limits") or []:
        lines.append(f"- Limit: {limit}")
    lines.append("")
    lines.append("## Measured model outputs")
    lines.append("")
    lines.append(f"- Result: `{a.get('result', 'MISSING')}`")
    lines.append(f"- Seed: {inputs.get('seed', 'MISSING')}; cases: "
                 f"{inputs.get('cases', 'MISSING')}; draws: {inputs.get('draws', 'MISSING')}")
    lines.append(f"- Oracle checks recorded: {sum(counts.values())} "
                 f"across {len(counts)} named oracles")
    for name, err in sorted((a.get("max_errors") or {}).items()):
        lines.append(f"- Max error, {name}: {err}")
    lines.append("- Preregistered tolerances (thresholds fixed before the run, "
                 "not chosen post hoc):")
    for name, tol in sorted((a.get("tolerances") or {}).items()):
        lines.append(f"  - {name}: {tol}")
    lines.append("")
    lines.append("## Inference")
    lines.append("")
    lines.append("The synthetic reference model agreed with its independent "
                 "oracles inside the preregistered tolerances above. That is "
                 "evidence about the model's internal consistency only. This "
                 "is a synthetic simulation: it is not a production result, "
                 "and no production benefit is claimed from it.")
    lines.append("")
    lines.append("## Recommendation")
    lines.append("")
    lines.append("None for production. Do not enable exploration, choose "
                 "production thresholds, or cite simulated benefit from this "
                 "artifact alone; production adoption is a separately "
                 "authorized stage with its own evidence.")
    lines.append("")
    lines.append("## Missing measurements")
    lines.append("")
    if missing:
        for name in missing:
            lines.append(f"- MISSING: {name} — the artifact does not carry it; "
                         "this report marks it instead of inventing it.")
    else:
        lines.append("None — every required measurement is present in the artifact.")
    lines.append("")
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(allow_abbrev=False)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    raw = args.input.read_bytes()
    text = render_report(load_artifact(raw), artifact_digest(raw))
    args.output.write_text(text, encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
